import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
const evidence = path.resolve('../docs/evidence/ui-redesign')
for (const role of ['student', 'lecturer'] as const) {
  test(`${role}: thẻ lớp, tìm kiếm, liên kết và điện thoại`, async ({ page }) => {
    await mkdir(evidence, { recursive: true })
    await page.goto('/login')
    await page.getByLabel('Tên đăng nhập', { exact: true }).fill(role === 'student' ? 'sv001' : 'gv001')
    await page.getByLabel('Mật khẩu', { exact: true }).fill('Demo@123')
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/${role}/dashboard`))
    await expect(page.getByRole('heading', { name: role === 'student' ? 'Hôm nay học gì?' : 'Hôm nay cần xử lý gì?' })).toBeVisible()
    await page.screenshot({ path: path.join(evidence, `${role}-dashboard-desktop.png`), fullPage: true })
    await page.setViewportSize({ width: 375, height: 812 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
    await page.screenshot({ path: path.join(evidence, `${role}-dashboard-mobile.png`), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`/${role}/classes`)
    await expect(page.getByRole('link', { name: 'Vào lớp' }).first()).toBeVisible()
    await expect(page.getByLabel('Đang tải công việc')).toHaveCount(0)
    await page.screenshot({ path: path.join(evidence, `${role}-desktop.png`), fullPage: true })
    await page.getByLabel('Tìm kiếm lớp học').fill('khong-co-lop-nay-123')
    await expect(page.getByText(/Không tìm thấy lớp phù hợp/)).toBeVisible()
    await page.getByLabel('Tìm kiếm lớp học').fill('')
    await expect(page.getByRole('link', { name: 'Vào lớp' }).first()).toBeVisible()
    await page.getByRole('link', { name: 'Thông báo lớp' }).first().click()
    await expect(page.getByRole('navigation', { name: 'Điều hướng lớp học' })).toBeVisible()
    await expect(page.locator('.animate-pulse')).toHaveCount(0)
    await page.screenshot({ path: path.join(evidence, `${role}-class-menu-desktop.png`), fullPage: true })
    await page.getByRole('button', { name: 'Học tập', exact: true }).click()
    await page.getByRole('tab', { name: 'Bài tập', exact: true }).click()
    await expect(page).toHaveURL(/tab=assignments/)
    await page.goto(`/${role}/classes`)
    await expect(page.getByRole('link', { name: 'Vào lớp' }).first()).toBeVisible()
    await page.setViewportSize({ width: 375, height: 812 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
    await page.screenshot({ path: path.join(evidence, `${role}-mobile.png`), fullPage: true })
    await page.evaluate(() => document.documentElement.classList.add('dark'))
    await page.screenshot({ path: path.join(evidence, `${role}-mobile-dark.png`), fullPage: true })
    await page.getByRole('link', { name: 'Thông báo lớp' }).first().click()
    await expect(page).toHaveURL(new RegExp(`/${role}/classes/\\d+\\?tab=announcements`))
    await expect(page.getByRole('navigation', { name: 'Điều hướng lớp học' })).toBeVisible()
    await expect(page.locator('.animate-pulse')).toHaveCount(0)
    await page.screenshot({ path: path.join(evidence, `${role}-class-menu-mobile.png`), fullPage: true })
    await page.getByRole('button', { name: 'Học tập', exact: true }).click()
    await page.getByLabel('Mục trong lớp', { exact: true }).selectOption('assignments')
    await expect(page).toHaveURL(/tab=assignments/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()

  })
}
test('admin: điều hướng lớp theo nhóm trên điện thoại', async ({ page }) => {
  await mkdir(evidence, { recursive: true })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/login')
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill('admin')
  await page.getByLabel('Mật khẩu', { exact: true }).fill('Demo@123')
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/dashboard/)
  await expect(page.getByRole('heading', { name: 'Tổng quan quản trị' })).toBeVisible()
  await page.screenshot({ path: path.join(evidence, 'admin-dashboard-mobile.png'), fullPage: true })
  await page.goto('/admin/classes/1')
  await expect(page.getByRole('navigation', { name: 'Điều hướng lớp học' })).toBeVisible()
  await page.getByRole('button', { name: 'Thành viên', exact: true }).click()
  await page.getByLabel('Mục trong lớp', { exact: true }).selectOption('students')
  await expect(page).toHaveURL(/tab=students/)
  await expect(page.locator('.animate-pulse')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: path.join(evidence, 'admin-class-menu-mobile.png'), fullPage: true })
})

