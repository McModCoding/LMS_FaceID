import { test, expect, Page, APIRequestContext } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

const evidence = path.resolve('../docs/evidence/phase1')
const demoPassword = process.env.PHASE1_DEMO_PASSWORD || 'Demo@123'
const run = process.env.PHASE1_RUN || Date.now().toString(36)
const reason = `Xin vắng kiểm thử G1 ${run}`
