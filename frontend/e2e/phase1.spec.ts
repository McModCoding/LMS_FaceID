async function auth(request: APIRequestContext, username: string, password = demoPassword) {
  const res = await request.post('/api/v1/auth/login', { data: { username, password } })
  expect(res.ok()).toBeTruthy()
  return { Authorization: `Bearer ${(await res.json()).access_token}` }
}
async function login(page: Page, username: string) {
  await page.goto('/login')
  await page.getByLabel('Tên đăng nhập', { exact: true }).fill(username)
  await page.getByLabel('Mật khẩu', { exact: true }).fill(demoPassword)
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login$/)
}
async function openClass(page: Page, role: 'admin' | 'lecturer' | 'student', tab: string, classId = 1) {
  await page.goto(`/${role}/classes/${classId}`)
  await page.getByRole('tab', { name: tab, exact: true }).click()
}
async function shot(page: Page, name: string) {
  await mkdir(evidence, { recursive: true })
  if (!name.endsWith('-loading')) await page.getByLabel('Đang tải', { exact: true }).waitFor({ state: 'hidden' })
  await page.screenshot({ path: path.join(evidence, name + '.png'), fullPage: true, animations: 'disabled' })
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
}

