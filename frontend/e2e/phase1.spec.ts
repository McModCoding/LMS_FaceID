test('G1-1.2 — tạo lớp, ghi danh, sinh buổi và từ chối trùng lịch', async ({ page, request }) => {
  const admin = await auth(request, 'admin')
  const original = await (await request.get('/api/v1/classes/1', { headers: admin })).json()
  const students = await (await request.get('/api/v1/classes/1/students', { headers: admin })).json()
  const future = await (await request.get('/api/v1/classes/1/sessions?status=scheduled&page_size=100', { headers: admin })).json()
  const date = future.items[0].date
  const res = await request.post('/api/v1/classes', { headers: admin, data: {
    code: `G1-${run}`, subject_id: original.subject_id, semester_id: original.semester_id,
    lecturer_id: original.lecturer_id, max_students: 1,
  } })
  expect(res.status()).toBe(201)
  const created = await res.json()
  const added = await request.post(`/api/v1/classes/${created.id}/students`, { headers: admin, data: { student_ids: [students.items[0].student_id] } })
  expect(added.ok()).toBeTruthy()
  const full = await request.post(`/api/v1/classes/${created.id}/students`, { headers: admin, data: { student_ids: [students.items[1].student_id] } })
  expect(full.status()).toBeGreaterThanOrEqual(400)
  const weekday = (new Date(`${date}T12:00:00Z`).getUTCDay() + 6) % 7
  const timetable = await (await request.get(`/api/v1/admin/timetable?from_date=${date}&to_date=${date}`, { headers: admin })).json()
  const hour = [17, 18, 19, 20, 21, 22].find(h => !timetable.items.some((item: { start_time: string; end_time: string }) => item.start_time < `${h + 1}:00:00` && item.end_time > `${h}:00:00`))!
  expect(hour).toBeTruthy()
  const schedule = { weekday, start_time: `${hour}:00`, end_time: `${hour + 1}:00`, room: `G1-${run}`, start_date: date, end_date: date }
  expect((await request.post(`/api/v1/classes/${created.id}/schedules`, { headers: admin, data: schedule })).ok()).toBeTruthy()
  expect((await request.post(`/api/v1/classes/${created.id}/activate`, { headers: admin })).ok()).toBeTruthy()
  await login(page, 'admin')
  await openClass(page, 'admin', 'Lịch & Buổi học', created.id)
  await expect(page.getByText(`G1-${run} ·`, { exact: false }).first()).toBeVisible()
  await shot(page, 'task-1.2-created-schedule')
  await page.getByRole('button', { name: 'Thêm lịch học', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox').click()
  await page.getByRole('option').nth(weekday).click()
  for (const [name, value] of Object.entries({ start_time: schedule.start_time, end_time: schedule.end_time, room: schedule.room, start_date: date, end_date: date })) {
    await dialog.locator(`input[name="${name}"]`).fill(value)
  }
  await dialog.getByRole('button', { name: 'Tạo lịch & Sinh buổi', exact: true }).click()
  await expect(page.getByRole('alertdialog').getByText('Trùng phòng', { exact: true })).toBeVisible()
  await shot(page, 'task-1.2-schedule-conflict')
})

